let lang = 'nl'

function t(key) {
  return copy[lang][key] ?? copy.nl[key] ?? key
}

function waUrl(size) {
  const text = copy[lang].wa[size] ?? copy.nl.wa[size]
  return `https://wa.me/${WHATSAPP_E164}?text=${encodeURIComponent(text)}`
}

function refreshWhatsAppLinks() {
  document.querySelectorAll('[data-wa]').forEach((el) => {
    const size = el.getAttribute('data-wa')
    if (size === '2kg' || size === '5kg') {
      el.setAttribute('href', waUrl(size))
      el.setAttribute('target', '_blank')
      el.setAttribute('rel', 'noopener noreferrer')
    }
  })
}

function applyLanguage(next) {
  lang = next
  document.documentElement.lang = next

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    const value = t(key)
    if (value) el.textContent = value
  })

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt')
    const value = t(key)
    if (value) el.setAttribute('alt', value)
  })

  document.title = t('meta.title')
  const meta = document.querySelector('meta[name="description"]')
  if (meta) meta.setAttribute('content', t('meta.description'))

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    const active = btn.dataset.lang === lang
    btn.classList.toggle('is-active', active)
    btn.setAttribute('aria-pressed', String(active))
  })

  refreshWhatsAppLinks()
}

function setupReveal() {
  const nodes = document.querySelectorAll(
    '.story .section-copy, .story .section-figure, .season-intro, .season-stage, .bleed-photo, .products-head, .products-copy, .products .section-figure, .delivery .section-copy, .delivery .section-figure, .order-shell',
  )
  nodes.forEach((n) => n.classList.add('reveal'))

  if (!('IntersectionObserver' in window)) {
    nodes.forEach((n) => n.classList.add('is-visible'))
    return
  }

  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible')
          io.unobserve(entry.target)
        }
      })
    },
    { threshold: 0.14, rootMargin: '0px 0px -8% 0px' },
  )

  nodes.forEach((n) => io.observe(n))
}

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => applyLanguage(btn.dataset.lang))
})

applyLanguage('nl')
setupReveal()
